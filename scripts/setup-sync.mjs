// One-time setup for syncing progress across browsers and VMs.
//
// Progress lives in a secret GitHub Gist. The page talks to the GitHub API
// with a token that can only read and write gists. That token and the gist id
// are encrypted with your passphrase (PBKDF2-SHA256 -> AES-256-GCM) and saved
// to sync-config.js, which is safe to commit: signing in on any browser means
// typing the passphrase, which decrypts the token locally.
//
//   node scripts/setup-sync.mjs               create a new gist
//   node scripts/setup-sync.mjs --gist <id>   reuse a gist (new token or passphrase)
import { createInterface } from 'node:readline';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SYNC_FILE = 'cyberpath-progress.json';
export const ITERATIONS = 600000;
const CONFIG_PATH = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'sync-config.js');

const b64 = bytes => Buffer.from(bytes).toString('base64');

export async function encryptConfig(secret, passphrase, iterations = ITERATIONS) {
  const { subtle } = globalThis.crypto;
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const base = await subtle.importKey('raw', new TextEncoder().encode(passphrase), 'PBKDF2', false, ['deriveKey']);
  const key = await subtle.deriveKey({ name: 'PBKDF2', salt, iterations, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
  const data = await subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(JSON.stringify(secret)));
  return { v: 1, iterations, salt: b64(salt), iv: b64(iv), data: b64(data) };
}

export function configScript(config) {
  return '// Generated by scripts/setup-sync.mjs. The sync token and gist id, encrypted with your passphrase.\n' +
    `window.CYBERPATH_SYNC=${JSON.stringify(config)};\n`;
}

// One readline for the whole run; its line iterator buffers piped input.
let rl, lines, muted = false;
async function ask(question, hidden = false) {
  if (!rl) {
    rl = createInterface({ input: process.stdin, output: process.stdout, terminal: Boolean(process.stdin.isTTY) });
    const write = rl._writeToOutput.bind(rl);
    rl._writeToOutput = text => { if (!muted) write(text); };
    lines = rl[Symbol.asyncIterator]();
  }
  process.stdout.write(question);
  muted = hidden; // stop echoing what is typed
  const { value, done } = await lines.next();
  muted = false;
  if (hidden || !process.stdin.isTTY) process.stdout.write('\n');
  if (done) throw new Error('Input ended before every answer was given');
  return value.trim();
}

async function github(token, method, path, body) {
  const response = await fetch('https://api.github.com' + path, {
    method,
    headers: {
      Authorization: 'Bearer ' + token,
      Accept: 'application/vnd.github+json',
      ...(body ? { 'Content-Type': 'application/json' } : {}),
    },
    body: body && JSON.stringify(body),
  });
  if (!response.ok) {
    const detail = await response.text().catch(() => '');
    throw new Error(`GitHub ${method} ${path} failed with ${response.status}. ${detail.slice(0, 200)}`);
  }
  return response.json();
}

async function main() {
  const gistFlag = process.argv.indexOf('--gist');
  let gist = gistFlag > -1 ? process.argv[gistFlag + 1] : null;
  if (gistFlag > -1 && !gist) throw new Error('--gist needs a gist id');

  console.log('CyberPath sync setup');
  console.log('Token: create a fine-grained token at https://github.com/settings/personal-access-tokens/new');
  console.log('with Account permissions > Gists: Read and write and nothing else.');
  console.log('(A classic token with only the "gist" scope also works.)\n');

  const token = await ask('GitHub token (hidden): ', true);
  if (!token) throw new Error('No token entered');
  const passphrase = await ask('Sync passphrase, 12+ characters (hidden): ', true);
  if (passphrase.length < 12) throw new Error('Use at least 12 characters. The encrypted token is public, so the passphrase is the only lock.');
  if (await ask('Repeat passphrase (hidden): ', true) !== passphrase) throw new Error('Passphrases do not match');

  if (gist) {
    const existing = await github(token, 'GET', '/gists/' + gist);
    if (!existing.files?.[SYNC_FILE]) throw new Error(`Gist ${gist} has no ${SYNC_FILE} file`);
    console.log('Using existing gist ' + gist);
  } else {
    const initial = { version: 1, rev: 'init', savedAt: new Date().toISOString(), data: { done: [], labs: {}, quiz: {}, answers: {}, last: null } };
    const created = await github(token, 'POST', '/gists', {
      description: 'CyberPath progress (synced by the course site)',
      public: false,
      files: { [SYNC_FILE]: { content: JSON.stringify(initial) } },
    });
    gist = created.id;
    console.log('Created secret gist ' + gist);
  }

  await writeFile(CONFIG_PATH, configScript(await encryptConfig({ token, gist }, passphrase)));
  console.log('\nWrote sync-config.js. Publish it so every browser can sign in:');
  console.log('  git add sync-config.js && git commit -m "Set up progress sync" && git push');
  console.log('\nThen open the site, choose Sign in and enter the passphrase.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => {
    console.error('\n' + error.message);
    process.exitCode = 1;
  }).finally(() => rl?.close());
}
